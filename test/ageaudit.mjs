import { loadBH } from './loader.mjs';
const BH = loadBH(undefined, false);
const RULES = [
  [/幼儿园/, 3, 6], [/红领巾|小学/, 6, 13], [/军训|校服|中学|初中|高中|高三|班主任|补习班|月考|晚自习|教室|校门口|教导主任|班级|全班|同学录|校园/, 11, 19],
  [/高考|准考证/, 16, 20], [/大学|宿舍|室友|食堂|社团|辅导员|选修|学分|毕业论文|学士/, 17, 25],
  [/实习/, 19, 25], [/面试|简历|offer|入职|公司|同事|领导|加班|项目|周报|年终奖|年会|工位|部门|裁员|优化|老板|创业|投资人|出差/, 20, 68],
  [/相亲|彩礼/, 23, 48], [/你的婚礼|接亲|婚纱|蜜月|领证/, 23, 65],
  [/你的孩子|你儿子|你女儿|家长会|辅导作业|亲子|开家长|接孩子|孩子的作业/, 25, 72],
  [/退休|返聘/, 52, 78], [/广场舞/, 50, 88], [/孙/, 50, 95],
];
let bad = 0;
for (const e of BH.EVENTS) {
  for (const [re, lo, hi] of RULES) {
    if (re.test(e.t)) {
      if (e.a[0] < lo - 2 || e.a[1] > hi + 2) {
        console.log(`⚠ [${e.id}] a=[${e.a}] 应≈[${lo},${hi}] :: ${e.t.slice(0, 38)}`);
        bad++;
      }
      break;
    }
  }
}
console.log(`\n可疑事件: ${bad}/${BH.EVENTS.length}`);
